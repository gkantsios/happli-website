// Builds worker/snapshot-zips.ts, the ZIP → city / state / metro table the Snapshot Worker uses at
// submit time (no outside lookup API). Run it by hand when refreshing the data; it isn't part of the build.
//
//   node scripts/build-zip-regions.mjs <US.txt> <list1.csv>
//
// Inputs:
// - US.txt: GeoNames US postal codes (https://download.geonames.org/export/zip/US.zip, CC BY 4.0).
//   Tab-separated: country, zip, place name, state name, state code, county name, county FIPS, …
// - list1.csv: the Census Bureau's CBSA delineation file (List 1, July 2023, public domain), saved from
//   https://www2.census.gov/programs-surveys/metro-micro/geographies/reference-files/2023/delineation-files/list1_2023.xlsx
//   as CSV with only the data rows (columns A–L: CBSA code, division, CSA, CBSA title, metro/micro,
//   division title, CSA title, county, state name, state FIPS, county FIPS, central/outlying).
//
// Only Metropolitan Statistical Areas count as a "metro". Micropolitan areas are small enough that a
// metro bucket would be little bigger than a town, so those ZIPs fall back straight to the state.
import { readFileSync, writeFileSync } from 'node:fs';

const [usPath, cbsaPath] = process.argv.slice(2);
if (!usPath || !cbsaPath) throw new Error('usage: node scripts/build-zip-regions.mjs <US.txt> <list1.csv>');

const FIPS = {
  AL: '01', AK: '02', AZ: '04', AR: '05', CA: '06', CO: '08', CT: '09', DE: '10', DC: '11', FL: '12', GA: '13', HI: '15',
  ID: '16', IL: '17', IN: '18', IA: '19', KS: '20', KY: '21', LA: '22', ME: '23', MD: '24', MA: '25', MI: '26', MN: '27',
  MS: '28', MO: '29', MT: '30', NE: '31', NV: '32', NH: '33', NJ: '34', NM: '35', NY: '36', NC: '37', ND: '38', OH: '39',
  OK: '40', OR: '41', PA: '42', RI: '44', SC: '45', SD: '46', TN: '47', TX: '48', UT: '49', VT: '50', VA: '51', WA: '53',
  WV: '54', WI: '55', WY: '56',
};
// The 2023 file uses Connecticut's planning regions; GeoNames still has some old county codes.
const CT_OLD = { '001': '14860', '003': '25540', '007': '25540', '009': '35300', '011': '35980', '013': '25540' };

const parseCsv = (line) => {
  const out = [];
  let cur = '', q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
};

const metroByCounty = new Map();
const metroLabel = new Map();
for (const line of readFileSync(cbsaPath, 'utf8').split(/\r?\n/)) {
  if (!line.trim()) continue;
  const [code, , , title, kind, , , , , stateFips, countyFips] = parseCsv(line);
  if (kind !== 'Metropolitan Statistical Area') continue;
  metroByCounty.set(stateFips.padStart(2, '0') + countyFips.padStart(3, '0'), code);
  // "Dallas-Fort Worth-Arlington, TX" → "Dallas"
  metroLabel.set(code, title.split(',')[0].split('-')[0].trim());
}

const cities = new Map(); // "OK|Tulsa" → { zips: [], metros: Map<code, count> }
for (const line of readFileSync(usPath, 'utf8').split(/\r?\n/)) {
  const [, zip, place, , state, , county] = line.split('\t');
  if (!zip || !FIPS[state] || !/^\d{5}$/.test(zip)) continue;
  const metro = metroByCounty.get(FIPS[state] + county) ?? (state === 'CT' ? CT_OLD[county] : undefined) ?? '';
  const key = `${state}|${place.trim()}`;
  if (!cities.has(key)) cities.set(key, { zips: [], metros: new Map() });
  const c = cities.get(key);
  c.zips.push(zip);
  c.metros.set(metro, (c.metros.get(metro) ?? 0) + 1);
}

const usedMetros = new Set();
const cityRows = [...cities.entries()].sort(([a], [b]) => a.localeCompare(b));
const zipRows = [];
const cityOut = cityRows.map(([key, c], i) => {
  // A city whose ZIPs straddle a metro line takes the metro most of its ZIPs are in.
  const metro = [...c.metros.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0][0];
  if (metro) usedMetros.add(metro);
  for (const z of c.zips) zipRows.push([z, i]);
  return `${key}|${metro}`;
});
if (cityOut.length >= 36 ** 3) throw new Error('too many cities for 3-character indexes');
zipRows.sort((a, b) => a[0].localeCompare(b[0]));
const metroOut = [...usedMetros].sort().map((code) => `${code}|${metroLabel.get(code)}`);
const zipOut = zipRows.map(([z, i]) => z + i.toString(36).padStart(3, '0')).join('');

const ts = `// Generated by scripts/build-zip-regions.mjs. Do not edit by hand.
// ZIP and city data: GeoNames (https://www.geonames.org/, CC BY 4.0). Metro areas: U.S. Census Bureau
// CBSA delineation, July 2023 (Metropolitan Statistical Areas only).
// ${zipRows.length} ZIPs, ${cityOut.length} cities, ${metroOut.length} metros.

/** "CBSA code|short name", ";"-separated. */
export const METROS = ${JSON.stringify(metroOut.join(';'))};
/** "ST|City|CBSA code (or empty)", ";"-separated. A city's position is its index. */
export const CITIES = ${JSON.stringify(cityOut.join(';'))};
/** Sorted 8-character records: the 5-digit ZIP, then its city index in base 36 (3 characters). */
export const ZIPS = ${JSON.stringify(zipOut)};
`;
writeFileSync(new URL('../worker/snapshot-zips.ts', import.meta.url), ts);
console.log(`build-zip-regions: ${zipRows.length} ZIPs, ${cityOut.length} cities, ${metroOut.length} metros`);
